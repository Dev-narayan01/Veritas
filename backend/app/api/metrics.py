"""``/api/metrics``: serve the evaluation artifacts produced by ``ml/evaluate.py``.

The Evaluation page renders only what these files contain.  Nothing is computed,
resampled or invented here; the service exists so the frontend does not need to
bundle multi-megabyte JSON.
"""

from __future__ import annotations

import json

from fastapi import APIRouter

from ..artifacts import registry
from ..config import REPO_ROOT, settings
from ..logging_setup import get_logger

log = get_logger(__name__)
router = APIRouter(tags=["metrics"])

ARTIFACT_FILES = (
    "metrics.json",
    "robustness.json",
    "bias.json",
    "baseline.json",
    "cross_generator.json",
    "plag_benchmark_results.json",
    "plag_thresholds.json",
    "embedding_projection.json",
    "thresholds.json",
    "manifest.json",
    "split_manifest.json",
)


def _load(name: str) -> dict | list | None:
    path = registry.artifact_file(name)
    if path is None:
        return None
    try:
        return json.loads(path.read_text())
    except json.JSONDecodeError as exc:
        log.warning("artifact %s is not valid JSON: %s", name, exc)
        return None


@router.get("/metrics")
def metrics() -> dict:
    """Every evaluation artifact plus the list of available plot images."""
    registry.load()
    payload: dict[str, object] = {
        "artifact_source": registry.source,
        "data_source": registry.data_source,
        "manifest": registry.manifest,
        "plots": [],
    }
    for name in ARTIFACT_FILES:
        payload[name.replace(".json", "")] = _load(name)
    plots_dir = (registry.dir / "plots") if registry.dir else None
    if plots_dir and plots_dir.exists():
        payload["plots"] = sorted(p.name for p in plots_dir.glob("*.png"))
    payload["plots_base"] = "/api/metrics/plots" if plots_dir else None
    return payload


@router.get("/metrics/plots/{name}")
def plot(name: str):  # noqa: ANN201 - FileResponse
    """Serve a plot image from the artifact bundle (name is validated)."""
    from fastapi.responses import FileResponse

    from fastapi import HTTPException

    if "/" in name or ".." in name or not name.endswith(".png"):
        raise HTTPException(status_code=404, detail="plot not found")
    directory = registry.dir / "plots" if registry.dir else None
    if directory is None or not (directory / name).exists():
        raise HTTPException(status_code=404, detail="plot not found")
    return FileResponse(directory / name, media_type="image/png")


@router.get("/samples")
def samples() -> list[dict[str, str]]:
    """The two "Try a sample" buttons on the Analyze page.

    Looks in ``data/samples`` first (a user may drop their own) and falls back to the
    bundled corpus generated by ``scripts/make_bundled_corpus.py``, so a fresh clone
    still has something to click without shipping anyone else's documents.
    """
    directories = [settings.data_path / "samples", REPO_ROOT / "ml" / "bundled" / "samples"]
    out: list[dict[str, str]] = []
    for name, label in (("sample_human.txt", "Sample: human-written"), ("sample_ai.txt", "Sample: AI-written")):
        for directory in directories:
            path = directory / name
            if path.exists():
                out.append({"label": label, "text": path.read_text()[:20_000]})
                break
    return out
