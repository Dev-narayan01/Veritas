#!/usr/bin/env python3
"""Bundle the Lite core into each Vercel function's own directory.

Vercel's Python builder packages a function as *only* the entrypoint module: a sibling
``api/_lib/core.py`` is never uploaded, so ``from _lib.core import ...`` fails at runtime
with ``ModuleNotFoundError`` while the build log stays green. The only layout the builder
handles reliably is a self-contained single file.

So this script copies ``api/_lib/core.py`` to ``api/_core.py`` before every deploy. The
functions then do ``from _core import ...``, which sits in the same directory and is
therefore part of the bundle. ``api/_core.py`` is generated (git-ignored); ``api/_lib/core.py``
stays the single source of truth and is what the test suite imports.
"""

from __future__ import annotations

import sys
from pathlib import Path

API = Path(__file__).resolve().parent.parent / "api"
SOURCE = API / "_lib" / "core.py"
TARGET = API / "_core.py"

HEADER = '''"""Generated by scripts/sync_api_core.py - do not edit.

Vercel ships each function as a single file, so the shared Lite core has to live next to
the functions that import it. Edit ``api/_lib/core.py`` instead and run
``python scripts/sync_api_core.py`` (the deploy scripts do this automatically).
"""
'''


def main() -> int:
    if not SOURCE.is_file():
        print(f"missing {SOURCE}", file=sys.stderr)
        return 1
    body = SOURCE.read_text(encoding="utf-8")
    # Drop the module docstring so the generated file does not stack two of them.
    if body.startswith('"""'):
        end = body.find('"""', 3)
        if end != -1:
            body = body[end + 3 :].lstrip("\n")
    TARGET.write_text(HEADER + "\n" + body, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(API.parent)} ({TARGET.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
